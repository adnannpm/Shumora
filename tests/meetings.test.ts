import { expect, it, vi } from 'vitest'
import { MeetingManager } from '../src/main/meetings'
const participants = [{ id: 'a', name: 'Design', role: 'Design' }, { id: 'b', name: 'Code', role: 'Engineering' }]
const input = { agenda: 'Launch', participants, leader: 'b', language: 'en' as const }
const tick = () => new Promise(resolve => setTimeout(resolve, 0))
it('runs automatic turns but invites the user between rounds and before the summary', async () => {
  const prompt = vi.fn(async (_id: string, text: string) => `Reply ${text.includes('Reply') ? 'with context' : 'first'}`)
  const manager = new MeetingManager({ status: () => 'ready', prompt }, () => {})
  manager.start(input)
  for (let i = 0; i < 10; i++) await tick()
  expect(prompt.mock.calls.map(c => c[0])).toEqual(['b', 'a'])
  expect(manager.snapshot()).toMatchObject({ phase: 'paused', awaitingUser: true })
  manager.direction('Can we launch without animations?')
  for (let i = 0; i < 10; i++) await tick()
  expect(prompt.mock.calls[2][1]).toContain('Can we launch without animations?')
  expect(prompt.mock.calls[2][1]).toContain('Address the user')
  expect(manager.snapshot()).toMatchObject({ phase: 'paused', awaitingUser: true })
  manager.resume()
  for (let i = 0; i < 10; i++) await tick()
  expect(prompt.mock.calls.map(c => c[0])).toEqual(['b', 'a', 'b', 'a', 'b'])
  expect(prompt.mock.calls[1][1]).toContain('Reply first')
  expect(prompt.mock.calls[4][1]).toContain('SUMMARY')
  expect(manager.snapshot().phase).toBe('completed')
  expect(manager.snapshot().messages).toHaveLength(6)
})
it('pauses after the active response and suppresses late continuation after stop', async () => {
  let resolve!: (text: string) => void
  const prompt = vi.fn(() => new Promise<string>(r => { resolve = r }))
  const manager = new MeetingManager({ status: () => 'ready', prompt }, () => {})
  manager.start(input); manager.pause(); resolve('First'); await tick()
  expect(prompt).toHaveBeenCalledTimes(1)
  expect(manager.snapshot().phase).toBe('paused')
  manager.resume(); await tick()
  expect(prompt).toHaveBeenCalledTimes(2)
  manager.stop(); resolve('Late'); await tick()
  expect(prompt).toHaveBeenCalledTimes(2)
  expect(manager.snapshot().phase).toBe('stopped')
  expect(manager.snapshot().messages).toHaveLength(1)
})
it('rejects disconnected agents and duplicate starts, and exposes provider failures', async () => {
  const status = vi.fn(() => 'disconnected')
  const manager = new MeetingManager({ status, prompt: async () => { throw new Error('Provider failed') } }, () => {})
  expect(() => manager.start(input)).toThrow('not ready')
  status.mockReturnValue('ready')
  manager.start(input)
  expect(() => manager.start(input)).toThrow('already active')
  await tick()
  expect(manager.snapshot()).toMatchObject({ phase: 'paused', error: 'Provider failed' })
})
it('validates participants and preserves user directions and takeover', async () => {
  const manager = new MeetingManager({ status: () => 'ready', prompt: async () => 'View' }, () => {})
  expect(() => manager.start({ ...input, participants: [participants[0], participants[0]] })).toThrow()
  manager.start(input); manager.pause(); await tick(); manager.takeOver(); manager.direction('Focus MVP')
  expect(manager.snapshot().leader).toBe('user')
  expect(manager.snapshot().messages.at(-1)).toMatchObject({ author: 'You', text: 'Focus MVP' })
  manager.stop()
})
